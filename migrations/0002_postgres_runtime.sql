CREATE OR REPLACE FUNCTION trosa.compat_current_user() RETURNS text
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('trade_os.user', true), ''), 'hamid')
$$;

CREATE OR REPLACE FUNCTION trosa.compat_normalized_name(value text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
    SELECT trim(regexp_replace(regexp_replace(lower(coalesce(value, '')), '[^a-z0-9]+', ' ', 'g'), '\s+', ' ', 'g'))
$$;

CREATE OR REPLACE FUNCTION trosa.compat_domain(value text) RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    result text := lower(trim(coalesce(value, '')));
BEGIN
    IF result = '' THEN RETURN ''; END IF;
    result := regexp_replace(result, '^https?://', '');
    result := split_part(result, '/', 1);
    result := split_part(result, '@', 2);
    result := split_part(result, ':', 1);
    RETURN regexp_replace(result, '^www\.', '');
END
$$;

CREATE OR REPLACE FUNCTION trosa.compat_uuid(seed text) RETURNS uuid
LANGUAGE sql IMMUTABLE AS $$
    SELECT (substr(md5(coalesce(seed, '')), 1, 8) || '-' ||
            substr(md5(coalesce(seed, '')), 9, 4) || '-' ||
            substr(md5(coalesce(seed, '')), 13, 4) || '-' ||
            substr(md5(coalesce(seed, '')), 17, 4) || '-' ||
            substr(md5(coalesce(seed, '')), 21, 12))::uuid
$$;

