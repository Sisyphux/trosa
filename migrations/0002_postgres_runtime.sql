CREATE OR REPLACE FUNCTION trosa.compat_customers_write() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    legacy_user text := trosa.compat_current_user();
    legacy_customer_id bigint;
    company_id uuid;
    account_id uuid;
    company_name text;
    normalized_name text;
    country text;
    website text;
    dom text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        UPDATE trosa.accounts
           SET deleted_at=now(),updated_at=now()
         WHERE id=(SELECT ar.account_id FROM trosa.account_legacy_refs ar
                   WHERE ar.organization_id='859a998d-1b48-589b-8035-34dc65c01440'::uuid
                     AND ar.legacy_user_id=legacy_user AND ar.legacy_customer_id=OLD.id);
        RETURN OLD;
    END IF;

    legacy_customer_id := CASE WHEN TG_OP='INSERT' AND (NEW.id IS NULL OR NEW.id=0)
        THEN (SELECT coalesce(max(ar.legacy_customer_id),0)+1 FROM trosa.account_legacy_refs ar
              WHERE ar.organization_id='859a998d-1b48-589b-8035-34dc65c01440'::uuid AND ar.legacy_user_id=legacy_user)
        ELSE NEW.id END;
    company_name := coalesce(nullif(trim(NEW.company),''), nullif(trim(NEW.name),''), 'UNKNOWN');
    normalized_name := trosa.compat_normalized_name(company_name);
    country := coalesce(NEW.country,'');
    website := coalesce(NEW.website,'');
    dom := trosa.compat_domain(website);

    IF dom <> '' THEN
        SELECT d.company_id INTO company_id FROM core.company_domains d
         WHERE d.normalized_domain=dom LIMIT 1;
    ELSE
        SELECT c.id INTO company_id FROM core.companies c
         WHERE c.organization_id='859a998d-1b48-589b-8035-34dc65c01440'::uuid
           AND c.normalized_name=normalized_name AND c.country_code=country LIMIT 1;
    END IF;
    IF company_id IS NULL THEN
        company_id := trosa.compat_uuid(CASE WHEN dom<>'' THEN 'company:domain:'||dom
                                             ELSE 'company:name:'||normalized_name||'|'||trosa.compat_normalized_name(country) END);
        INSERT INTO core.companies(id,organization_id,canonical_name,normalized_name,website,country_code)
        VALUES (company_id,'859a998d-1b48-589b-8035-34dc65c01440'::uuid,company_name,normalized_name,website,country)
        ON CONFLICT (id) DO UPDATE SET canonical_name=excluded.canonical_name,
          normalized_name=excluded.normalized_name,website=excluded.website,country_code=excluded.country_code,updated_at=now();
    ELSE
        UPDATE core.companies SET canonical_name=company_name,website=website,country_code=country,updated_at=now()
         WHERE id=company_id AND (TG_OP='INSERT' OR coalesce(NEW.company,'')<>'');
    END IF;
    IF dom<>'' THEN
        INSERT INTO core.company_domains(id,company_id,normalized_domain,source_url,is_primary,verification_status)
        VALUES (trosa.compat_uuid('company-domain:'||dom),company_id,dom,website,true,'imported')
        ON CONFLICT (company_id,normalized_domain) DO UPDATE SET source_url=excluded.source_url;
    END IF;
    account_id := trosa.compat_uuid('account:'||company_id::text);
    INSERT INTO trosa.accounts(id,organization_id,company_id,display_name,account_status,customer_type,channel_type,priority_level,profile,field,industry,company_size,annual_revenue,tags,attention_state,attention_reason,last_contact_at,next_follow_up_at,deleted_at,legacy_payload,updated_at)
    VALUES (account_id,'859a998d-1b48-589b-8035-34dc65c01440'::uuid,company_id,coalesce(NEW.name,''),coalesce(NEW.status,''),coalesce(NEW.customer_type,'existing'),coalesce(NEW.type,''),coalesce(NEW.level,'C'),coalesce(NEW.profile,''),coalesce(NEW.field,''),coalesce(NEW.industry,''),coalesce(NEW.company_size,''),coalesce(NEW.annual_revenue,''),coalesce(NEW.tags,''),coalesce(NEW.attention_state,''),coalesce(NEW.attention_reason,''),NULLIF(NEW.last_contact,'')::timestamptz,NULLIF(NEW.next_follow_up,'')::timestamptz,CASE WHEN coalesce(NEW.is_deleted,0)=1 THEN now() ELSE NULL END,coalesce(to_jsonb(NEW),'{}'::jsonb),now())
    ON CONFLICT (organization_id,company_id) DO UPDATE SET display_name=excluded.display_name,account_status=excluded.account_status,customer_type=excluded.customer_type,channel_type=excluded.channel_type,priority_level=excluded.priority_level,profile=excluded.profile,field=excluded.field,industry=excluded.industry,company_size=excluded.company_size,annual_revenue=excluded.annual_revenue,tags=excluded.tags,attention_state=excluded.attention_state,attention_reason=excluded.attention_reason,last_contact_at=excluded.last_contact_at,next_follow_up_at=excluded.next_follow_up_at,deleted_at=excluded.deleted_at,legacy_payload=trosa.accounts.legacy_payload || excluded.legacy_payload,updated_at=now();
    INSERT INTO trosa.account_legacy_refs(organization_id,legacy_user_id,legacy_customer_id,account_id,source_db)
    VALUES ('859a998d-1b48-589b-8035-34dc65c01440'::uuid,legacy_user,legacy_customer_id,account_id,legacy_user||'.db')
    ON CONFLICT (organization_id,legacy_user_id,legacy_customer_id) DO UPDATE SET account_id=excluded.account_id;
    PERFORM trosa.compat_set_lastrowid(legacy_customer_id);
    RETURN NEW;
END
$$;

